/**
 * **开页自动开演**：进页面不等任何人点，先把第一个例子演一遍。
 *
 * ## 为什么需要它
 *
 * 演示站点是"发出去给人看"的东西，而**第一印象只能给一次**。
 * 开页停在一张静止的工艺图上，看图的人默认它是一张图片 ——
 * 得有人先告诉他"下面那排按钮可以点"，他才会去点。
 * 自动演一遍讲稿（镜头推近 + 图元高亮）把这件事**直接演出来**：
 * 看完就知道这张图是活的、会跟着话走。
 *
 * ## 为什么是一个开关，而不是"开页就去演"
 *
 * 因为**本地开发不该被它打扰**。`npm run dev` 每次刷新都自动演 19 秒、
 * 面板里多出一屏消息，调试时会很烦。所以跟 `transport.ts` 同一套两级优先：
 *
 * | 来源 | 怎么表达 |
 * |---|---|
 * | 构建期默认 | 演示构建（`npm run build:demo`）默认开 |
 * | 运行期覆盖 | `?autoplay=1` / `?autoplay=0` |
 *
 * 普通 `npm run build` 的默认是**关**，所以本地开发与 e2e 的行为与加这个开关之前一致。
 *
 * ## 与"演示模式"是两个独立的轴
 *
 * `?demo=` 管的是**事件从哪儿来**（浏览器里的剧本 / 远端后端），
 * `?autoplay=` 管的是**开页要不要自己动**。两个都可以单独覆盖：
 *
 * ```
 * ?demo=1&autoplay=0   # 纯前端，但安静地等我点
 * ?demo=0&autoplay=1   # 连后端，开页就自己演一遍
 * ```
 *
 * ⚠️ 默认值上它们**有一处交叉**：构建期默认还要求"这次真的走着纯前端那条路"
 * （见 boot.ts 的 `AUTOPLAY`）—— 因为演示构建上若把 `?demo=0` 打开，后端可能压根没起，
 * 开页自动演就会自动弹一张错误卡。第一印象不该是一张错误卡。
 * 显式写 `?autoplay=1` 时不受这条限制：用户点了名要看，那就演给他看。
 */

/** 自动开演时用的那句话 —— 与「工艺图」那组的第一个快捷按钮**同一条**。 */
export const AUTOPLAY_OPENING = '看看污水处理工艺图';

/**
 * 判定开页要不要自动演一遍。**纯函数**（`search` 与构建期默认都从外面传），
 * 所以优先级能被穷举测掉。
 *
 * 非法值（`?autoplay=whatever`）落回构建期默认 —— 与 `?demo=` / `?theme=` 同一口径：
 * 分享链接手抖打错一个参数不该让页面行为变得不可预期。
 */
export function resolveAutoplay(search: string, buildDefault: boolean): boolean {
  const wanted = new URLSearchParams(search).get('autoplay');
  if (wanted === '1' || wanted === 'true') return true;
  if (wanted === '0' || wanted === 'false') return false;
  return buildDefault;
}
